import { readFileSync, writeFileSync } from 'fs';
import { resolve } from 'path';
import { runMigrations } from '@gami/database';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { registeredRoutes, buildServer } from '../index.js';
import { resolveProjectPermission } from '../authorization/permissions.js';

const DOC = resolve(import.meta.dirname, '../../../../docs/permissions.md');

/** Builds the table from the routes the server really registers, so it cannot drift. */
function buildMatrix(): string {
  const seen = new Set<string>();
  const rows: string[] = [];

  const routes = registeredRoutes
    .filter((route) => route.url.startsWith('/api/projects/:projectId') && route.method !== 'HEAD' && route.method !== 'OPTIONS')
    .sort((a, b) => a.url.localeCompare(b.url) || a.method.localeCompare(b.method));

  for (const route of routes) {
    const key = `${route.method} ${route.url}`;
    if (seen.has(key)) continue;
    seen.add(key);

    const permission = resolveProjectPermission(route.method, route.url);
    const path = route.url.replace('/api/projects/:projectId', '') || '/';
    const access = permission.sessionOnly ? 'Signed-in user only' : `API key with \`${permission.scope}\``;
    rows.push(`| \`${route.method}\` | \`${path}\` | ${permission.minRole === 'admin' ? 'Admin' : 'Member'} | ${access} |`);
  }

  return [
    '<!-- Generated by apps/api/src/__tests__/permissions-doc.test.ts. Do not edit by hand. -->',
    '<!-- Regenerate with: UPDATE_DOCS=1 pnpm --filter @gami/api exec vitest run src/__tests__/permissions-doc.test.ts -->',
    '',
    '# Project route permissions',
    '',
    'Every route under `/api/projects/:projectId` and the lowest organization role and credential it accepts. The rules live in `apps/api/src/authorization/permissions.ts`, and a route that rule does not recognise is closed to API keys and needs an admin. This table is generated from the routes the server registers, and a test fails when it is out of date.',
    '',
    '| Method | Path | Lowest role | Credential |',
    '| :--- | :--- | :--- | :--- |',
    ...rows,
    '',
  ].join('\n');
}

describe('permissions documentation', () => {
  let app: Awaited<ReturnType<typeof buildServer>>;

  beforeAll(async () => {
    await runMigrations();
    app = await buildServer();
    await app.ready();
  });

  afterAll(async () => {
    await app.close();
  });

  it('matches the routes the server registers', () => {
    const generated = buildMatrix();
    expect(generated.split('\n').length).toBeGreaterThan(30);

    if (process.env['UPDATE_DOCS'] === '1') {
      writeFileSync(DOC, generated);
      return;
    }
    const current = readFileSync(DOC, 'utf8').replace(/\r\n/g, '\n');
    expect(current, 'docs/permissions.md is out of date. Regenerate it with UPDATE_DOCS=1.').toBe(generated);
  });
});
